# Step 4: writes MatchModels.inc and MatchBaseStats.inc (in the repo root) from out/stats.csv and models/mlp.pkl.
# Run steps 2 and 4 twice after changing a level fit or the areas: some tables are percentiles of numbers the others feed.
# Writes the generated tables the plugin compiles in: rank baselines, the level estimate and the scoring-chance model.
import warnings; warnings.simplefilter("ignore")
import pandas as pd, numpy as np, io, pickle, os
def fl(x, d=6):
    t = ('%%.%dg' % d) % x
    if '.' not in t and 'e' not in t and 'n' not in t: t += '.0'
    return t + 'f'
from cols import *
from sklearn.linear_model import RidgeCV
OUT=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..')+os.sep   # the repo root, where Match.cpp is
L=open('out/stats.csv').read().split('\n')
P=pd.read_csv(io.StringIO('\n'.join(l for l in L if l.startswith('P,'))),names=PCOLS)
P['r']=P['rank'].map({r:i for i,r in enumerate(RANKS)})
# impact: chance added minus the lobby's average (the same as Match.cpp works it out)
P['impact']=P['chanceAdded']-P.groupby('rid')['chanceAdded'].transform('mean')
# (field, per five minutes?, +1 higher is better / -1 lower is better / 0 neither)
STATS=[('touches',1,0),('goals',1,1),('assists',1,1),('chanceAdded',1,1),('impact',1,1),('shots',1,1),('saves',1,0),('passes',1,1),('clears',1,0),('giveaways',1,-1),('giveDangerous',1,-1),('fifties',1,0),
 ('doubleCommits',1,-1),('beaten',1,-1),('leftNetOpen',1,-1),('stolenPads',1,1),('aerialsWon',1,1),('shadows',1,1),('boostUsed',1,0),
 ('supersonicBoost',1,-1),('boostWasted',1,-1),('noBoostSecs',1,-1),('bigPads',1,0),('smallPads',1,1),('avgBoost',0,0),('supersonicPct',0,1),
 ('airPct',0,0),('avgSpeed',0,1),('behindBallPct',0,0),('stoppedPct',0,-1),('bunchedPct',0,-1),('recoverSecs',0,-1),('demosTaken',1,-1),
 ('goalSideTheirsPct',0,1),('farFromPlayPct',0,-1),('supportBack',0,-1),('flatPct',0,0),('supportDist',0,0),('lastDefDepth',0,0),('lastAttDepth',0,0),
 ('level',0,1),('posLevel',0,1)]
AREAS=[[('goals',0),('shots',0),('assists',0)],
 [('goalSideTheirsPct',0),('leftNetOpen',0),('beaten',0),('recoverSecs',0),('shadows',0)],
 [('giveaways',0),('giveDangerous',0),('passes',1)],
 [('posLevel',0),('farFromPlayPct',0),('doubleCommits',1),('bunchedPct',1),('supportBack',1)],
 [('boostWasted',0),('noBoostSecs',0),('supersonicBoost',0),('smallPads',0)],
 [('supersonicPct',0),('avgSpeed',0),('stoppedPct',0)]]
def pct_of(q,v):   # the same as PctOf in Match.cpp
    P5=[10,25,50,75,90]
    lo=max([k for k in range(5) if q[k]<v],default=-1); hi=min([k for k in range(5) if q[k]>v],default=5)
    if hi-lo>1: return float(np.mean(P5[lo+1:hi]))
    if lo<0: return max(1.0,10-(q[0]-v)*15/(q[1]-q[0])) if q[1]>q[0] else 5.0
    if hi>4: return min(99.0,90+(v-q[4])*15/(q[4]-q[3])) if q[4]>q[3] else 95.0
    return P5[lo]+(P5[hi]-P5[lo])*(v-q[lo])/(q[hi]-q[lo])
for f,p5,_ in STATS:
    P['v_'+f]=P[f]*300/P['seconds'] if p5 else P[f]
with open(OUT+'MatchBaseStats.inc','w') as o:
    o.write('// Generated by tools/match/gen.py from ranked replays. Do not edit by hand.\n')
    for f,_,_ in STATS: o.write('\tBase_%s,\n'%f)
with open(OUT+'MatchModels.inc','w') as o:
    o.write('// Generated by tools/match/gen.py from %d ranked replays (gold to supersonic legend, 1v1 2v2 3v3). Do not edit by hand.\n'%P['rid'].nunique())
    o.write('static float BaseValue(const MatchPlayerStats& s, int stat, float seconds)\n{\n\tconst float per5 = seconds > 1.0f ? 300.0f / seconds : 0.0f;\n\tswitch (stat)\n\t{\n')
    for i,(f,p5,_) in enumerate(STATS): o.write('\tcase %d: return static_cast<float>(s.%s)%s;\n'%(i,f,' * per5' if p5 else ''))
    o.write('\tdefault: return 0.0f;\n\t}\n}\n')
    o.write('static const int kBaseBetter[] = { %s };\n'%', '.join(str(b) for _,_,b in STATS))
    o.write('static const bool kBasePer5[] = { %s };\n'%', '.join('true' if p else 'false' for _,p,_ in STATS))
    o.write('// [team size - 1][rank: gold..supersonic legend][stat][10th, 25th, 50th, 75th, 90th percentile]\n')
    o.write('static const float kBase[3][6][%d][5] = {\n'%len(STATS))
    for ts in (1,2,3):
        o.write('{\n')
        for r in range(6):
            D=P[(P.teamSize==ts)&(P.r==r)]
            o.write(' {')
            for f,_,_ in STATS:
                q=np.percentile(D['v_'+f],[10,25,50,75,90])
                o.write('{'+','.join(fl(x) for x in q)+'},')
            o.write('},\n')
        o.write('},\n')
    o.write('};\n')
    # level estimate: a straight-line fit from the numbers that climb with rank
    LF=['avgSpeed','supersonicPct','airPct','stoppedPct','touches','aerialsWon','boostUsed','smallPads','bigPads','saves','shots','fifties','avgBoost','doubleCommits','bunchedPct','leftNetOpen','passes']
    idx=[ [s[0] for s in STATS].index(f) for f in LF]
    o.write('static const int kLevelN = %d;\nstatic const int kLevelStat[] = { %s };\n'%(len(LF),', '.join(map(str,idx))))
    rows=[]; icpt=[]
    for ts in (1,2,3):
        D=P[P.teamSize==ts]; X=D[['v_'+f for f in LF]].values; y=D['r'].values
        mu,sd=X.mean(0),X.std(0)+1e-9
        m=RidgeCV(alphas=[1,10,100]).fit((X-mu)/sd,y)
        w=m.coef_/sd; b=m.intercept_-(m.coef_*mu/sd).sum()
        rows.append(w); icpt.append(b)
    o.write('static const float kLevelW[3][%d] = {\n'%len(LF)+''.join(' {'+','.join(fl(x) for x in w)+'},\n' for w in rows)+'};\n')
    o.write('static const float kLevelB[3] = { '+', '.join(fl(b) for b in icpt)+' };\n')
    # positioning level: the same kind of fit from positioning numbers only (1v1 uses the first two)
    PF=['goalSideTheirsPct','farFromPlayPct','stoppedPct','leftNetOpen','bunchedPct','supportBack']
    pidx=[[x[0] for x in STATS].index(f) for f in PF]
    o.write('static const int kPosN = %d;\nstatic const int kPosStat[] = { %s };\n'%(len(PF),', '.join(map(str,pidx))))
    rows=[]; icpt=[]
    for ts in (1,2,3):
        F=PF[:2] if ts==1 else PF
        D=P[P.teamSize==ts]; X=D[['v_'+f for f in F]].values; y=D['r'].values
        mu,sd=X.mean(0),X.std(0)+1e-9
        m=RidgeCV(alphas=[1,10,100]).fit((X-mu)/sd,y)
        w=list(m.coef_/sd)+[0.0]*(len(PF)-len(F)); b=m.intercept_-(m.coef_*mu/sd).sum()
        rows.append(w); icpt.append(b)
    o.write('static const float kPosW[3][%d] = {\n'%len(PF)+''.join(' {'+','.join(fl(x) for x in w)+'},\n' for w in rows)+'};\n')
    o.write('static const float kPosB[3] = { '+', '.join(fl(b) for b in icpt)+' };\n')
    # touch grades and Play labels: cut-offs from every judged touch's swing (the W rows)
    W=np.array([float(x) for l in L if l.startswith('W,') for x in l.strip().split(',')[3:]])
    tc=[np.percentile(W,q) for q in (99.5,90,10,3.5,0.5)]
    o.write('// touch grades from the swing: Calculated (top 0.5%%), Clean (top 10%%), Solid, Sloppy (bottom 10%%), Costly (bottom 3.5%%), Throw (bottom 0.5%%). %d touches.\n'%len(W))
    o.write('static const float kTouchCut[5] = { '+', '.join(fl(x) for x in tc)+' };\n')
    o.write('static const float kPlayCalculated = %s, kPlayGreat = %s, kPlayWhoops = %s, kPlayBlunder = %s;   // the labels: top 0.5%%, next 3%%, bottom 3.5%%, bottom 0.5%%\n'%(fl(np.percentile(W,99.5)),fl(np.percentile(W,96.5)),fl(np.percentile(W,3.5)),fl(np.percentile(W,0.5))))
    # the review's areas: (stat, team modes only). Their scores' cut-offs per mode and rank.
    names=[x[0] for x in STATS]; better={x[0]:x[2] for x in STATS}
    o.write('static const int kAreaN[6] = { %s };\n'%', '.join(str(len(a)) for a in AREAS))
    o.write('static const int kAreaStat[6][6] = {\n'+''.join(' { '+', '.join('Base_'+f for f,_ in a)+(', -1'*(6-len(a)))+' },\n' for a in AREAS)+'};\n')
    o.write('static const bool kAreaTeam[6][6] = {\n'+''.join(' { '+', '.join('true' if t else 'false' for _,t in a)+(', false'*(6-len(a)))+' },\n' for a in AREAS)+'};\n')
    o.write('// [team size - 1][rank][area, then the whole game][3rd, 10th, 25th, 75th, 95th percentile of the score]\n')
    o.write('static const float kAreaCut[3][6][7][5] = {\n')
    for ts in (1,2,3):
        o.write('{\n')
        for r in range(6):
            D=P[(P.teamSize==ts)&(P.r==r)]
            B={f:np.percentile(D['v_'+f],[10,25,50,75,90]) for f in names}
            scores=[[] for _ in range(7)]
            for _,row in D.iterrows():
                tot=0
                for ai,a in enumerate(AREAS):
                    vals=[]
                    for f,team in a:
                        if team and ts==1: continue
                        if f=='recoverSecs' and row['recoverSecs']<=0: continue
                        p=pct_of(B[f],row['v_'+f]); vals.append(100-p if better[f]<0 else p)
                    sc=np.mean(vals) if vals else 50.0
                    scores[ai].append(sc); tot+=sc
                imp=pct_of(B['impact'],row['v_impact'])
                scores[6].append((tot+imp)/7)
            o.write(' {'+''.join('{'+','.join(fl(x,4) for x in np.percentile(sc,[3,10,25,75,95]))+'},' for sc in scores)+'},\n')
        o.write('},\n')
    o.write('};\n')
    # scoring-chance model
    ml=pickle.load(open('models/mlp.pkl','rb'))
    W=ml.coefs_; B=ml.intercepts_
    o.write('// scoring chance: %d inputs -> %d -> %d -> 1 (relu, then a logistic). P(this team scores in the next 10 s).\n'%(W[0].shape[0],W[0].shape[1],W[1].shape[1]))
    def mat(n,a): return 'static const float %s[%d][%d] = {\n'%(n,a.shape[0],a.shape[1])+''.join(' {'+','.join(fl(x) for x in r)+'},\n' for r in a)+'};\n'
    def vec(n,a): return 'static const float %s[%d] = { '%(n,len(a))+','.join(fl(x) for x in a)+' };\n'
    o.write('static const int kChH1 = %d, kChH2 = %d;\n'%(W[0].shape[1],W[1].shape[1]))
    o.write(mat('kChW1',W[0].T)+vec('kChB1',B[0])+mat('kChW2',W[1].T)+vec('kChB2',B[1])+vec('kChW3',W[2][:,0])+'static const float kChB3 = %s;\n'%fl(B[2][0]))
print('ok', len(STATS))
